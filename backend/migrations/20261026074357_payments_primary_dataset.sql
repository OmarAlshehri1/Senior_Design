language plpgsql security invoker set search_path='' as $$
begin
 if old.state='READY' and to_jsonb(old) is distinct from to_jsonb(new) then
   raise exception 'Ready dataset metadata is sealed' using errcode='55000'; end if;
 return new;
end; $$;
