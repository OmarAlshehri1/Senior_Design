-- Templates contain only fixed rule language and fixed eligibility fields.
-- Per-payment evidence is reconstructed from exact typed fields, never omitted.
create function public.primary_rule_results(t public.transactions) returns jsonb
language sql stable security invoker set search_path='' as $$
    select jsonb_agg(p.payload || jsonb_build_object('evidence',
        (p.payload->'evidence') || case p.ordinal
          when 1 then case when p.failed then jsonb_build_object('excess_amount',(t.amount-t.approval_limit)::text) else '{}'::jsonb end
          when 2 then jsonb_build_object('matching_transaction_count',t.primary_duplicate_count)
          when 3 then jsonb_build_object('historical_transaction_count',t.primary_window_count,
              'window_total_amount',t.primary_window_total::text)
          else '{}'::jsonb end) order by p.ordinal)
    from public.primary_datasets d join public.primary_rule_templates p on p.version=d.rule_template_version
    where d.id=t.dataset_id and p.failed=((t.primary_rule_mask::integer & (1<<p.ordinal))<>0);
$$;
revoke all on function public.primary_rule_results(public.transactions) from public,anon,authenticated;
grant execute on function public.primary_rule_results(public.transactions) to service_role;

