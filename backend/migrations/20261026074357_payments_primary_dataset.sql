create function public.import_primary_payment_batch(p_dataset smallint,p_batch integer,p_rows jsonb)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare d public.primary_datasets; prior public.primary_import_batches;
    fingerprint text; n integer; inserted integer;
begin
    select * into d from public.primary_datasets where id=p_dataset for update;
    if not found or d.id=0 or d.state<>'IMPORTING' then raise exception 'Dataset not importable' using errcode='22023'; end if;
    if jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows) not between 1 and 2000 then
        raise exception 'Bounded nonempty rows required' using errcode='22023'; end if;
    if pg_database_size(current_database())>420000000 then raise exception 'Free-plan import headroom reached' using errcode='54000'; end if;
    n:=jsonb_array_length(p_rows);
    if (select count(distinct x->>'id') from jsonb_array_elements(p_rows)x)<>n then raise exception 'Duplicate batch IDs' using errcode='22023'; end if;
    fingerprint:=encode(sha256(convert_to(p_rows::text,'UTF8')),'hex');
    select * into prior from public.primary_import_batches where dataset_id=p_dataset and batch_number=p_batch;
    if found then
        if prior.content_sha256<>fingerprint then raise exception 'Batch content changed' using errcode='23505'; end if;
        return jsonb_build_object('accepted',prior.row_count,'duplicate',true);
    end if;
    insert into public.transactions(id,transaction_timestamp,vendor_id,vendor_name,invoice_number,category,amount,currency,
        created_by,approved_by,approver_role,approval_limit,completeness_status,missing_fields,metadata,ground_truth,
        dataset_id,source_row,contract_reference,primary_rule_mask,primary_duplicate_count,primary_window_count,
        primary_window_total,primary_ai_scaled,primary_rule_scaled,primary_risk_scaled,primary_raw_severity)
    select x.id,x.transaction_timestamp,x.vendor_id,x.vendor_name,x.invoice_number,x.category,x.amount,x.currency,
        x.created_by,x.approved_by,x.approver_role,x.approval_limit,x.completeness_status,x.missing_fields,
        coalesce(x.metadata,'{}'), '{}',p_dataset,x.source_row,x.contract_reference,x.primary_rule_mask,
        x.primary_duplicate_count,x.primary_window_count,x.primary_window_total,x.primary_ai_scaled,
        x.primary_rule_scaled,x.primary_risk_scaled,x.primary_raw_severity
    from jsonb_populate_recordset(null::public.transactions,p_rows)x;
    get diagnostics inserted=row_count;
    if inserted<>n then raise exception 'Incomplete batch'; end if;
    insert into public.primary_import_batches(dataset_id,batch_number,content_sha256,row_count)
        values(p_dataset,p_batch,fingerprint,n);
    return jsonb_build_object('accepted',n,'duplicate',false);
end; $$;
revoke all on function public.import_primary_payment_batch(smallint,integer,jsonb) from public,anon,authenticated;
grant execute on function public.import_primary_payment_batch(smallint,integer,jsonb) to service_role;

