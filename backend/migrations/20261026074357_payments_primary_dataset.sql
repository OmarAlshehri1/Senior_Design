    model_object text,
    model_threshold numeric(5,2) check(model_threshold between 0 and 100),
    rule_version text not null default '1.0.0',
    rule_template_version text not null default 'payments-primary-rules-1.0.0',
    risk_version text not null default '1.0.0',
    scored_at timestamptz,
    provenance jsonb not null default '{}',
    summary jsonb,
    created_at timestamptz not null default clock_timestamp()
