create or replace function public.get_authoritative_analytics(
    p_actor uuid,
    p_period_days integer default 30
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    profile public.user_profiles;
    result jsonb;
    utc_today date;
    period_start date;
begin
    select * into profile
    from public.user_profiles
    where id = p_actor and account_status = 'ACTIVE';
    if not found then
        raise exception 'Active account required' using errcode = '42501';
    end if;
    if p_period_days not in (7, 30, 90) then
        raise exception 'Unsupported analytics period' using errcode = '22023';
    end if;

    utc_today := (clock_timestamp() at time zone 'UTC')::date;
    period_start := utc_today - (p_period_days - 1);

    with rule_definitions(rule_key, rule_name) as (
        values
            ('segregation_of_duties', 'Segregation of Duties'),
            ('approval_limits', 'Approval Limits'),
            ('duplicate_payment', 'Duplicate Payments'),
            ('invoice_splitting', 'Invoice Splitting'),
            ('ghost_vendors', 'Ghost Vendors')
    ), latest_evaluations as materialized (
        select distinct on (e.transaction_id)
            e.transaction_id, e.rule_results, e.evaluated_at
        from public.application_evaluations e
        order by e.transaction_id, e.evaluated_at desc, e.id desc
    ), flattened as materialized (
        select
            e.transaction_id,
            e.evaluated_at,
            rr.value ->> 'rule_key' as rule_key,
            rr.value ->> 'status' as status,
            coalesce(rr.value -> 'evidence', '{}'::jsonb) as evidence
        from latest_evaluations e
        cross join lateral jsonb_array_elements(
            coalesce(e.rule_results, '[]'::jsonb)
        ) as rr(value)
    ), evaluation_counts as (
        select
            transaction_id,
            count(*) filter (where status in ('PASSED', 'FAILED')) as executed_count
        from flattened
        group by transaction_id
    ), transaction_counts as (
        select
            count(*) as total_transactions,
            count(*) filter (where coalesce(ec.executed_count, 0) = 5) as fully_evaluated,
            count(*) filter (where coalesce(ec.executed_count, 0) > 0 and ec.executed_count < 5) as partially_evaluated,
            count(*) filter (where coalesce(ec.executed_count, 0) = 0) as not_evaluated,
            count(*) filter (where coalesce(ec.executed_count, 0) > 0) as evaluated_transactions
        from public.application_transactions t
        left join evaluation_counts ec on ec.transaction_id = t.id
    ), rule_coverage as (
        select
            d.rule_key,
            d.rule_name,
            count(*) filter (where f.status in ('PASSED', 'FAILED')) as evaluated,
            count(*) filter (where f.status = 'NOT_EVALUATED' or f.status is null) as not_evaluated
        from rule_definitions d
        cross join public.application_transactions t
        left join flattened f on f.transaction_id = t.id and f.rule_key = d.rule_key
        group by d.rule_key, d.rule_name
    ), missing_snapshot_transactions as (
        select t.id as transaction_id
        from public.application_transactions t
        left join latest_evaluations e on e.transaction_id = t.id
        where e.transaction_id is null
    ), exclusion_rows as (
        select
            f.rule_key,
            case
                when jsonb_array_length(coalesce(f.evidence -> 'missing_fields', '[]'::jsonb)) > 0
                  or jsonb_array_length(coalesce(f.evidence -> 'missing_any_of', '[]'::jsonb)) > 0
                    then 'MISSING_REQUIRED_FIELDS'
                when f.evidence ->> 'historical_context_available' = 'false'
                  or f.evidence ->> 'vendor_registry_available' = 'false'
                    then 'RULE_CONTEXT_UNAVAILABLE'
                else 'RULE_NOT_EVALUATED'
            end as reason
        from flattened f
        where f.status = 'NOT_EVALUATED'
        union all
        select d.rule_key, 'EVALUATION_SNAPSHOT_MISSING'
        from missing_snapshot_transactions m
        cross join rule_definitions d
    ), exclusions as (
        select rule_key, reason, count(*) as transaction_count
        from exclusion_rows
        group by rule_key, reason
    ), daily_dates as (
        select generate_series(period_start, utc_today, interval '1 day')::date as bucket_date
    ), latest_daily_risk as (
        select distinct on (
            rs.transaction_id,
            (rs.calculated_at at time zone 'UTC')::date
        )
            rs.transaction_id,
            (rs.calculated_at at time zone 'UTC')::date as bucket_date,
            rs.risk_score,
            rs.risk_level
        from public.application_risk_scores rs
        where (rs.calculated_at at time zone 'UTC')::date between period_start and utc_today
        order by
            rs.transaction_id,
            (rs.calculated_at at time zone 'UTC')::date,
            rs.calculated_at desc,
            rs.id desc
    ), daily_risk as (
        select
            bucket_date,
            round(avg(risk_score), 2) as average_risk_score,
            count(*) filter (where risk_level = 'HIGH') as high_risk_transactions,
            count(*) filter (where risk_level = 'MEDIUM') as medium_risk_transactions,
            count(*) filter (where risk_level = 'LOW') as low_risk_transactions
        from latest_daily_risk
        group by bucket_date
    ), daily_alerts as (
        select (a.created_at at time zone 'UTC')::date as bucket_date, count(*) as alerts_created
        from public.application_alerts a
        where (a.created_at at time zone 'UTC')::date between period_start and utc_today
          and (profile.role = 'ADMIN' or public.can_access_team_alert(p_actor, a.id))
        group by 1
    ), daily_closures as (
        select
            (c.closed_at at time zone 'UTC')::date as bucket_date,
            count(*) filter (where c.resolution_outcome = 'ISSUE_CONFIRMED') as confirmed_issues,
            count(*) filter (where c.resolution_outcome = 'FALSE_POSITIVE') as false_positives
        from public.audit_cases c
        where c.closed_at is not null
          and (c.closed_at at time zone 'UTC')::date between period_start and utc_today
          and public.can_access_case(p_actor, c.id)
        group by 1
    ), daily_rule_violations as (
        select (f.evaluated_at at time zone 'UTC')::date as bucket_date, f.rule_key, count(*) as violations
        from flattened f
        where f.status = 'FAILED'
          and (f.evaluated_at at time zone 'UTC')::date between period_start and utc_today
        group by 1, 2
    ), coverage_json as (
        select jsonb_build_object(
            'total_transactions', tc.total_transactions,
            'fully_evaluated', tc.fully_evaluated,
            'partially_evaluated', tc.partially_evaluated,
            'not_evaluated', tc.not_evaluated,
            'evaluated_transactions', tc.evaluated_transactions,
            'coverage_percent', case when tc.total_transactions = 0 then 0
                else round(tc.evaluated_transactions::numeric / tc.total_transactions * 100, 2) end,
            'by_rule', coalesce((
                select jsonb_agg(jsonb_build_object(
                    'rule_key', rc.rule_key,
                    'rule_name', rc.rule_name,
                    'evaluated_transactions', rc.evaluated,
                    'not_evaluated_transactions', rc.not_evaluated,
                    'coverage_percent', case when tc.total_transactions = 0 then 0
                        else round(rc.evaluated::numeric / tc.total_transactions * 100, 2) end
                ) order by rc.rule_key)
                from rule_coverage rc
            ), '[]'::jsonb),
            'exclusions', coalesce((
                select jsonb_agg(jsonb_build_object(
                    'rule_key', ex.rule_key, 'reason', ex.reason, 'transaction_count', ex.transaction_count
                ) order by ex.rule_key, ex.reason)
                from exclusions ex
            ), '[]'::jsonb)
        ) as value
        from transaction_counts tc
    ), risk_json as (
        select coalesce(jsonb_agg(jsonb_build_object(
            'date', d.bucket_date,
            'average_risk_score', r.average_risk_score,
            'high_risk_transactions', coalesce(r.high_risk_transactions, 0),
            'medium_risk_transactions', coalesce(r.medium_risk_transactions, 0),
            'low_risk_transactions', coalesce(r.low_risk_transactions, 0),
            'alerts_created', coalesce(a.alerts_created, 0),
            'confirmed_issues', coalesce(c.confirmed_issues, 0),
            'false_positives', coalesce(c.false_positives, 0)
        ) order by d.bucket_date), '[]'::jsonb) as value
        from daily_dates d
        left join daily_risk r using (bucket_date)
        left join daily_alerts a using (bucket_date)
        left join daily_closures c using (bucket_date)
    ), rule_json as (
        select coalesce(jsonb_agg(jsonb_build_object(
            'date', d.bucket_date,
            'rule_key', defs.rule_key,
            'rule_name', defs.rule_name,
            'violations', coalesce(v.violations, 0)
        ) order by d.bucket_date, defs.rule_key), '[]'::jsonb) as value
        from daily_dates d
        cross join rule_definitions defs
        left join daily_rule_violations v on v.bucket_date = d.bucket_date and v.rule_key = defs.rule_key
    )
    select jsonb_build_object(
        'period_days', p_period_days,
        'period_start', period_start,
        'period_end', utc_today + 1,
        'coverage', coverage_json.value,
        'risk_trends', risk_json.value,
        'rule_violation_trends', rule_json.value
    ) into result
    from coverage_json
    cross join risk_json
    cross join rule_json;

    return result;
end;
$$;

