-- A sealed bulk result is immutable. Reviews/cases remain ordinary independent
-- append-only workflows and do not rewrite the transaction's scoring evidence.
create function public.protect_primary_payment_results() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
    if tg_op='INSERT' and new.primary_rule_mask is not null and exists(
      select 1 from public.primary_datasets d where d.id=new.dataset_id and d.state='READY') then
      raise exception 'Primary payment evidence is sealed' using errcode='55000';
    end if;
    if tg_op<>'INSERT' and old.primary_rule_mask is not null and exists(select 1 from public.primary_datasets d where d.id=old.dataset_id and d.state='READY')
      and to_jsonb(old) is distinct from to_jsonb(new) then
        raise exception 'Primary payment evidence is sealed' using errcode='55000';
    end if;
    if tg_op='DELETE' then return old; end if;
    return new;
end; $$;
revoke all on function public.protect_primary_payment_results() from public,anon,authenticated;
grant execute on function public.protect_primary_payment_results() to service_role;
create trigger protect_primary_payment_results before insert or update or delete on public.transactions
    for each row execute function public.protect_primary_payment_results();

create function public.seal_primary_dataset(p_dataset smallint) returns jsonb
language plpgsql security invoker set search_path='' as $$
declare d public.primary_datasets; actual bigint; total numeric; vendor_count bigint; s jsonb;
begin
    select * into d from public.primary_datasets where id=p_dataset for update;
    if not found or d.id=0 then raise exception 'Import dataset required' using errcode='22023'; end if;
    if d.state='READY' then return d.summary; end if;
    if d.source_schema<>'PAYMENTS_SIMULATION_WORKBOOK' or d.model_sha256 is null or d.model_version is null
      or d.model_bucket is null or d.model_object is null or d.scored_at is null or d.model_threshold is null then
        raise exception 'Model/source binding incomplete' using errcode='22023'; end if;
    select count(*),sum(amount) into actual,total from public.transactions where dataset_id=p_dataset;
    select count(*) into vendor_count from public.approved_vendors where dataset_id=p_dataset;
    if actual<>d.expected_rows or total is distinct from d.expected_amount or vendor_count<>d.expected_vendors then
        raise exception 'Dataset reconciliation failed' using errcode='22023'; end if;
    if exists(select 1 from public.transactions t where t.dataset_id=p_dataset and
      (t.primary_rule_mask is null or t.currency<>d.currency or not exists(select 1 from public.approved_vendors v where v.dataset_id=p_dataset and v.vendor_id=t.vendor_id))) then
        raise exception 'Missing compact result or reference' using errcode='22023'; end if;
    if pg_database_size(current_database())>420000000 then raise exception 'Free-plan reserve required' using errcode='54000'; end if;
    select jsonb_build_object('total',count(*),'amount_total',sum(amount),
      'risk_sum_scaled',coalesce(sum(primary_risk_scaled::bigint),0),
      'high',count(*) filter(where primary_risk_scaled>=7500),
      'medium',count(*) filter(where primary_risk_scaled>=5000 and primary_risk_scaled<7500),
      'low',count(*) filter(where primary_risk_scaled<5000),
      'failed_by_rule',jsonb_build_array(count(*) filter(where(primary_rule_mask&1)<>0),
        count(*) filter(where(primary_rule_mask&2)<>0),count(*) filter(where(primary_rule_mask&4)<>0),
        count(*) filter(where(primary_rule_mask&8)<>0),count(*) filter(where(primary_rule_mask&16)<>0)),
      'latest_source_timestamp',max(transaction_timestamp)) into s
    from public.transactions where dataset_id=p_dataset;
    update public.primary_datasets set state='READY',summary=s where id=p_dataset;
    return s;
end; $$;
